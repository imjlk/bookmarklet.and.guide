export type TemplateName = (typeof TEMPLATE_NAMES)[number];

export interface TemplateInfo {
  name: TemplateName;
  title: string;
  framework: string;
  language: string;
  description: string;
  recommendedFor: string;
}

export interface CreateProjectOptions {
  destination: string;
  template?: string;
  force?: boolean;
  local?: boolean;
}

export interface CreateProjectResult {
  dependencyMode: "local" | "published";
  destination: string;
  template: TemplateInfo;
  projectName: string;
  globalName: string;
  projectId: string;
  packageManager: string;
}

interface TemplateReplacements {
  bmklVersion: string;
  globalName: string;
  packageManager: string;
  projectId: string;
  projectName: string;
}

